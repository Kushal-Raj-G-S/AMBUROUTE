"""Regenerate docs/results_tables.md from the result CSVs, so the numbers quoted in the docs cannot drift from the runs.

    python experiments/make_docs_tables.py
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"


def md(df, floatfmt=2):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---:" if i else "---" for i in range(len(cols))) + "|"]
    for _, row in df.iterrows():
        cells = [f"{v:.{floatfmt}f}" if isinstance(v, float) else str(v) for v in row]
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def piv(df, index, columns, values, order=None, fmt=2):
    t = df.pivot_table(index=index, columns=columns, values=values, aggfunc="first")
    if order:
        t = t[[c for c in order if c in t.columns]]
    return md(t.reset_index(), fmt)


parts = ["# Result tables (generated)", "",
         "Generated by `experiments/make_docs_tables.py` from the CSVs in `results/`. Do not edit by hand; rerun the script. "
         "Narrative and caveats are in [`additional_studies.md`](additional_studies.md).", ""]

f = R / "module_ablation.csv"
if f.exists():
    d = pd.read_csv(f)
    d["p (corrected)"] = d.p_holm.map(lambda v: "" if pd.isna(v) else ("<0.001" if v < 0.001 else f"{v:.3f}"))
    parts += ["## Module ablation (mean minutes to bed, 50 test seeds)", "",
              md(d[["scenario", "variant", "ttb_mean", "rejections", "delta_pct", "p (corrected)"]].rename(
                  columns={"ttb_mean": "min to bed", "delta_pct": "vs full %"})), ""]
f = R / "ppo_warmstart_test.csv"
if f.exists():
    d = pd.read_csv(f)
    d = d[d.role.isin(["chosen", "reference"])]
    parts += ["## PPO warm start (chosen seed per variant, 50 test seeds)", "", md(d[["scenario", "model", "ttb_mean", "rejections"]]), ""]
f = R / "stress_rate_sweep.csv"
if f.exists():
    parts += ["## Call-rate sweep (mean minutes to bed)", "", piv(pd.read_csv(f), "rate", "policy", "ttb", ["nearest", "heuristic", "nash"]), ""]
f = R / "spatial_demand.csv"
if f.exists():
    d = pd.read_csv(f)
    parts += ["## Call locations: uniform vs building density (mean minutes to bed)", "",
              md(d.pivot_table(index=["scenario", "policy"], columns="demand", values="ttb").reset_index()), ""]
f = R / "online_summary.csv"
if f.exists():
    d = pd.read_csv(f)
    d = d[d.base == "heuristic"]
    parts += ["## Online adaptation (heuristic base, mean minutes to bed)", "",
              piv(d, ["drift", "scenario"], "variant", "ttb_mean", ["fixed model", "online (learned)", "oracle"]), ""]
f = R / "gnn_summary.csv"
if f.exists():
    d = pd.read_csv(f)
    parts += ["## Graph-network cost (mean minutes to bed, 50 test seeds)", "", md(d[["scenario", "policy", "ttb_mean", "rejections"]]), ""]
f = R / "clinical_researched.csv"
if f.exists():
    parts += ["## Clinical study with researched capabilities (critical patients, minutes to definitive care)", "",
              md(pd.read_csv(f)[["scenario", "policy", "crit", "spec", "transfer", "rejections"]]), ""]
f = R / "nyc_replay.csv"
if f.exists():
    parts += ["## Replay of real NYC arrival times (peak)", "", md(pd.read_csv(f)), ""]
f = R / "real_capacity_summary.csv"
if f.exists():
    d = pd.read_csv(f)
    parts += ["## Measured capacity (Bengaluru map, capacities drawn from real hospitals; mean minutes to bed)", "",
              piv(d, "scenario", "policy", "ttb", ["nearest", "capacity_heuristic", "nash", "ppo"]), ""]
f = R / "real_capacity_pressure.csv"
if f.exists():
    parts += ["## Benefit by capacity pressure (heuristic vs nearest)", "", md(pd.read_csv(f)), ""]
(ROOT / "docs" / "results_tables.md").write_text("\n".join(parts), encoding="utf-8")
print("wrote docs/results_tables.md", sum(1 for p in parts if p.startswith("## ")), "tables")
